def test_security_objects_present(app_engine: Engine) -> None:
    """Verify triggers and kalyan_app role privileges match security contracts."""
    with app_engine.connect() as conn:
        # 1. Triggers verification
        triggers = conn.execute(
            text("""
                SELECT tgname, relname
                FROM pg_trigger t
                JOIN pg_class c ON t.tgrelid = c.oid
                WHERE relname IN ('audit_logs', 'system_setup')
                  AND tgname LIKE 'trg_%'
            """)
        ).fetchall()

        trigger_map = {(row.relname, row.tgname) for row in triggers}
        expected_triggers = {
            ("audit_logs", "trg_audit_logs_no_update_delete"),
            ("audit_logs", "trg_audit_logs_no_truncate"),
            ("system_setup", "trg_system_setup_no_update_delete"),
            ("system_setup", "trg_system_setup_no_truncate"),
        }
        missing = expected_triggers - trigger_map
        assert expected_triggers.issubset(trigger_map), f"Missing triggers: {missing}"

        # 2. Least privilege role table grants for kalyan_app
        grants = conn.execute(
            text("""
                SELECT table_name, privilege_type
                FROM information_schema.role_table_grants
                WHERE grantee = 'kalyan_app'
                  AND table_schema = 'public'
            """)
        ).fetchall()

        table_privileges: dict[str, set[str]] = {}
        for row in grants:
            table_privileges.setdefault(row.table_name, set()).add(row.privilege_type)

        assert table_privileges.get("audit_logs") == {"SELECT", "INSERT"}
        assert table_privileges.get("system_setup") == {"SELECT", "INSERT"}
        assert table_privileges.get("users") == {"SELECT", "INSERT", "UPDATE"}
        assert "DELETE" not in table_privileges.get("users", set())
        assert table_privileges.get("doctors") == {"SELECT", "INSERT", "UPDATE"}
        assert table_privileges.get("login_throttle") == {"SELECT", "INSERT", "UPDATE"}
        assert table_privileges.get("sessions") == {"SELECT", "INSERT", "UPDATE", "DELETE"}
        assert table_privileges.get("clinic_settings") == {"SELECT", "INSERT", "UPDATE"}
        assert table_privileges.get("consultation_fees") == {"SELECT", "INSERT", "UPDATE"}
        assert table_privileges.get("urn_sequences") == {"SELECT", "INSERT", "UPDATE"}
        assert table_privileges.get("patients") == {"SELECT", "INSERT", "UPDATE"}
        assert table_privileges.get("alembic_version") == {"SELECT"}
